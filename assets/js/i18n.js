export function getCurrentLanguage() {
  const savedLanguage = localStorage.getItem('portfolio-language');
  return savedLanguage === 'en' ? 'en' : 'pt';
}

export function applyLanguage(language) {
  const currentLanguage = language === 'en' ? 'en' : 'pt';
  const strings = translations[currentLanguage];
  document.documentElement.lang = currentLanguage === 'pt' ? 'pt-BR' : 'en';

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = strings[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const value = strings[element.dataset.i18nAriaLabel];
    if (value !== undefined) element.setAttribute('aria-label', value);
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const value = strings[element.dataset.i18nAlt];
    if (value !== undefined) element.setAttribute('alt', value);
  });

  document.title = strings.siteTitle;
  document.querySelector('#meta-description').content = strings.metaDescription;
  document.querySelector('#og-title').content = strings.siteTitle;
  document.querySelector('#og-description').content = strings.metaDescription;
  localStorage.setItem('portfolio-language', currentLanguage);

  const languageButton = document.querySelector('#language-toggle');
  languageButton.textContent = currentLanguage === 'pt' ? 'EN' : 'PT';
  const actionLabel = currentLanguage === 'pt' ? 'Mudar idioma para inglês' : 'Switch language to Portuguese';
  languageButton.setAttribute('aria-label', actionLabel);
  languageButton.title = actionLabel;

  const menuToggle = document.querySelector('.menu-toggle');
  const menuIsOpen = menuToggle.getAttribute('aria-expanded') === 'true';
  menuToggle.setAttribute('aria-label', menuIsOpen ? strings.menuClose : strings.menuOpen);

  const themeIsDark = document.documentElement.dataset.theme === 'dark';
  const themeLabel = themeIsDark ? strings.activateLightTheme : strings.activateDarkTheme;
  const themeButton = document.querySelector('#theme-toggle');
  themeButton.setAttribute('aria-label', themeLabel);
  themeButton.title = themeLabel;
}
